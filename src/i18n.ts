const messages: Record<Language, typeof ko> = { ko, en };
let current: Language = "ko";

export function setLanguage(language: Language) { current = language; }
export function getCurrentLanguage(): Language { return current; }

export function t(key: keyof typeof ko, vars: Record<string, string> = {}): string {
  return messages[current][key].replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? "");
}
